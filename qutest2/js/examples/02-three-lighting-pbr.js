import { initThreeScene, disposeHierarchy } from '../utils/common.js';

export default {
  id: 'three-lighting-pbr',
  title: 'Studio Lighting, Shadows & PBR Materials',
  category: 'Three.js Fundamentals',
  badge: 'Three.js',
  badgeClass: 'badge-three',
  difficulty: 'Intermediate',
  description: 'Master Three.js physically based rendering (PBR), orbiting multi-colored point lights, shadow mapping, and surface reflectivity.',

  tutorial: {
    overview: `
      Physically Based Rendering (PBR) simulates real-world optical physics. In Three.js, <code>MeshStandardMaterial</code> and <code>MeshPhysicalMaterial</code> utilize the microfacet theory to model surface roughness, metallic conduction, and Fresnel light reflection.
      <br><br>
      Dynamic shadow maps are generated by rendering the scene from each light source's viewpoint into a shadow depth texture buffer.
    `,
    keyConcepts: [
      { name: 'THREE.SpotLight', desc: 'Emits light in a cone shape with adjustable penumbra (edge softness) and distance attenuation.' },
      { name: 'THREE.PointLight', desc: 'Emits light in all directions from a point in space (like a lightbulb).' },
      { name: 'THREE.PCFSoftShadowMap', desc: 'Percentage-Closer Filtering with Gaussian smoothing for ultra-soft realistic shadow edges.' },
      { name: 'Roughness vs Metalness', desc: 'Roughness spreads specular reflections; metalness determines whether reflectance is colored by the base diffuse pigment.' }
    ],
    tips: 'Move the light orbit speed slider to see dynamic specular highlights travel across the spheres and observe soft contact shadows on the floor.'
  },

  init(container, onStatsUpdate) {
    const { scene, camera, renderer, controls, cleanup } = initThreeScene(container, {
      cameraPos: [0, 4, 8],
      cameraTarget: [0, 1, 0],
      enableShadows: true
    });

    const params = {
      lightOrbitSpeed: 1.2,
      spotIntensity: 2.5,
      spotPenumbra: 0.8,
      spotColor: '#ffffff',
      pointIntensity: 2.0,
      roughness: 0.15,
      metalness: 0.9,
      showHelpers: false
    };

    // Ambient baseline
    const ambient = new THREE.AmbientLight(0x0f172a, 0.8);
    scene.add(ambient);

    // Main Spotlight
    const spotLight = new THREE.SpotLight(0xffffff, params.spotIntensity);
    spotLight.position.set(0, 8, 4);
    spotLight.angle = Math.PI / 4;
    spotLight.penumbra = params.spotPenumbra;
    spotLight.castShadow = true;
    spotLight.shadow.mapSize.width = 2048;
    spotLight.shadow.mapSize.height = 2048;
    spotLight.shadow.camera.near = 1;
    spotLight.shadow.camera.far = 25;
    spotLight.shadow.bias = -0.0005;
    scene.add(spotLight);

    // Moving colored Point Lights with glowing meshes (Purple & White theme)
    const lightData = [
      { color: 0xc084fc, radius: 4.2, speed: 1.0, yOffset: 1.8, phase: 0 },
      { color: 0xffffff, radius: 3.5, speed: -1.3, yOffset: 2.2, phase: Math.PI * 0.66 },
      { color: 0x8b5cf6, radius: 4.8, speed: 0.8, yOffset: 1.2, phase: Math.PI * 1.33 }
    ];

    const pointLights = lightData.map((d) => {
      const pl = new THREE.PointLight(d.color, params.pointIntensity, 15, 2);
      pl.castShadow = true;
      pl.shadow.mapSize.width = 512;
      pl.shadow.mapSize.height = 512;
      pl.shadow.bias = -0.002;

      // Visual bulb
      const bulbGeo = new THREE.SphereGeometry(0.12, 16, 16);
      const bulbMat = new THREE.MeshBasicMaterial({ color: d.color });
      const bulb = new THREE.Mesh(bulbGeo, bulbMat);
      pl.add(bulb);

      scene.add(pl);
      return { light: pl, ...d };
    });

    // PBR Objects in Studio
    const pbrMat = new THREE.MeshStandardMaterial({
      color: 0xffffff,
      roughness: params.roughness,
      metalness: params.metalness,
      envMapIntensity: 1.0
    });

    // Centerpiece: Multi-tiered composition
    const centerSphere = new THREE.Mesh(new THREE.SphereGeometry(1.2, 64, 64), pbrMat);
    centerSphere.position.set(0, 1.2, 0);
    centerSphere.castShadow = true;
    centerSphere.receiveShadow = true;
    scene.add(centerSphere);

    const torus = new THREE.Mesh(new THREE.TorusGeometry(1.9, 0.15, 32, 100), pbrMat);
    torus.position.set(0, 1.2, 0);
    torus.rotation.x = Math.PI / 3;
    torus.castShadow = true;
    torus.receiveShadow = true;
    scene.add(torus);

    // Surrounding pedestals and shapes
    const satelliteCount = 5;
    const satellites = [];
    for (let i = 0; i < satelliteCount; i++) {
      const angle = (i / satelliteCount) * Math.PI * 2;
      const x = Math.cos(angle) * 3.2;
      const z = Math.sin(angle) * 3.2;
      
      const geo = i % 2 === 0 ? new THREE.IcosahedronGeometry(0.5, 2) : new THREE.BoxGeometry(0.8, 0.8, 0.8);
      const m = new THREE.Mesh(geo, pbrMat);
      m.position.set(x, 0.5, z);
      m.castShadow = true;
      m.receiveShadow = true;
      scene.add(m);
      satellites.push({ mesh: m, baseAngle: angle });
    }

    // Reflective Studio Floor
    const floorGeo = new THREE.PlaneGeometry(30, 30);
    const floorMat = new THREE.MeshStandardMaterial({
      color: 0x0c0714,
      roughness: 0.35,
      metalness: 0.4
    });
    const floor = new THREE.Mesh(floorGeo, floorMat);
    floor.rotation.x = -Math.PI / 2;
    floor.position.y = 0;
    floor.receiveShadow = true;
    scene.add(floor);

    let animationFrameId = null;
    let isPaused = false;
    let simulatedTime = 0;
    let lastTime = performance.now();
    const CYCLE_DURATION = 10;

    function animate(now) {
      animationFrameId = requestAnimationFrame(animate);
      if (!lastTime) lastTime = now;
      const delta = Math.min((now - lastTime) / 1000, 0.1);
      lastTime = now;

      if (!isPaused) {
        simulatedTime += delta;
      }

      const t = simulatedTime * params.lightOrbitSpeed;

      // Animate orbiting point lights
      pointLights.forEach((p) => {
        const angle = t * p.speed + p.phase;
        p.light.position.x = Math.cos(angle) * p.radius;
        p.light.position.z = Math.sin(angle) * p.radius;
        p.light.position.y = p.yOffset + Math.sin(t * 1.5 + p.phase) * 0.6;
      });

      // Subtle rotation of center objects
      torus.rotation.z = t * 0.3;
      torus.rotation.y = t * 0.2;

      satellites.forEach((s, idx) => {
        s.mesh.rotation.y = t * (0.5 + idx * 0.1);
        s.mesh.rotation.x = t * (0.3 + idx * 0.1);
      });

      if (controls) controls.update();
      renderer.render(scene, camera);

      if (onStatsUpdate) {
        onStatsUpdate({
          activeLights: 4,
          shadowMaps: 'Enabled (PCF Soft)'
        });
      }
    }

    animate(performance.now());

    return {
      destroy() {
        if (animationFrameId) cancelAnimationFrame(animationFrameId);
        cleanup();
      },
      play() {
        isPaused = false;
        lastTime = performance.now();
      },
      pause() {
        isPaused = true;
      },
      restart() {
        simulatedTime = 0;
        isPaused = false;
        lastTime = performance.now();
      },
      seek(progressPercent) {
        simulatedTime = (progressPercent / 100) * CYCLE_DURATION;
      },
      getProgress() {
        return {
          progress: ((simulatedTime % CYCLE_DURATION) / CYCLE_DURATION) * 100,
          time: simulatedTime
        };
      },
      getControls() {
        return [
          {
            type: 'slider',
            label: 'Light Orbit Speed',
            min: 0,
            max: 3,
            step: 0.1,
            value: params.lightOrbitSpeed,
            onChange: (val) => { params.lightOrbitSpeed = parseFloat(val); }
          },
          {
            type: 'slider',
            label: 'Spotlight Intensity',
            min: 0,
            max: 6,
            step: 0.2,
            value: params.spotIntensity,
            onChange: (val) => {
              params.spotIntensity = parseFloat(val);
              spotLight.intensity = params.spotIntensity;
            }
          },
          {
            type: 'slider',
            label: 'Point Lights Intensity',
            min: 0,
            max: 5,
            step: 0.1,
            value: params.pointIntensity,
            onChange: (val) => {
              params.pointIntensity = parseFloat(val);
              pointLights.forEach(p => p.light.intensity = params.pointIntensity);
            }
          },
          {
            type: 'slider',
            label: 'Surface Roughness',
            min: 0.01,
            max: 1,
            step: 0.02,
            value: params.roughness,
            onChange: (val) => {
              params.roughness = parseFloat(val);
              pbrMat.roughness = params.roughness;
            }
          },
          {
            type: 'slider',
            label: 'Surface Metalness',
            min: 0,
            max: 1,
            step: 0.02,
            value: params.metalness,
            onChange: (val) => {
              params.metalness = parseFloat(val);
              pbrMat.metalness = params.metalness;
            }
          }
        ];
      },
      codeSnippet: `// 1. Enable soft shadow maps on renderer
renderer.shadowMap.enabled = true;
renderer.shadowMap.type = THREE.PCFSoftShadowMap;

// 2. Setup Spotlight with shadow casting
const spotLight = new THREE.SpotLight(0xffffff, 2.5);
spotLight.position.set(0, 8, 4);
spotLight.penumbra = 0.8;
spotLight.castShadow = true;
spotLight.shadow.mapSize.set(2048, 2048);
scene.add(spotLight);

// 3. Orbiting Point Light
const pointLight = new THREE.PointLight(0xc084fc, 2.0, 15);
pointLight.castShadow = true;
scene.add(pointLight);

// 4. PBR Standard Material
const pbrMat = new THREE.MeshStandardMaterial({
  color: 0xffffff,
  roughness: 0.15,
  metalness: 0.9
});
const mesh = new THREE.Mesh(geometry, pbrMat);
mesh.castShadow = true;
mesh.receiveShadow = true;
scene.add(mesh);`
    };
  }
};

